use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct HiveNode {
    pub id: String,
    pub title: String,
    #[serde(rename = "type")]
    pub node_type: String,
    pub layer: String,
    pub x: f32,
    pub y: f32,
    pub r: f32,
    pub sub: String,
    pub summary: String,
    pub sources: usize,
    #[serde(default)]
    pub branches: Vec<String>,
    pub tag: String,
}

